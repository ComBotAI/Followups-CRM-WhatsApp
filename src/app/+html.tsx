/**
 * Web only: the root HTML of every statically rendered page — search and
 * share metadata (title, description, Open Graph / Twitter card with the share
 * image), theme colour and icons. Runs in Node at build time, not in the browser.
 * A route's own `generateMetadata()` title / description replaces these defaults.
 */
import { ScrollViewStyleReset, useServerDocumentContext } from 'expo-router/html';
import { Children, isValidElement, type PropsWithChildren } from 'react';

import { env } from '@/config/env';
import { DEFAULT_DESCRIPTION, DEFAULT_TITLE, KEYWORDS, SHARE_IMAGE, SHARE_IMAGE_ALT, SITE, SITE_NAME } from '@/lib/seo';

/** Structured data: lets search engines show the app as a software product (name, category, price, platforms). */
const STRUCTURED_DATA = JSON.stringify({
  '@context': 'https://schema.org',
  '@graph': [
    {
      '@type': 'SoftwareApplication',
      name: SITE_NAME,
      url: SITE,
      image: SHARE_IMAGE,
      description: DEFAULT_DESCRIPTION,
      applicationCategory: 'BusinessApplication',
      applicationSubCategory: 'CRM',
      operatingSystem: 'Android, Web',
      inLanguage: ['en', 'hi', 'mr', 'gu', 'ta', 'te', 'bn', 'ur', 'ar', 'es', 'fr', 'de', 'pt', 'ru', 'id', 'zh', 'ja'],
      offers: { '@type': 'Offer', price: '0', priceCurrency: 'INR', description: 'Free to start' },
      publisher: { '@type': 'Organization', name: env.brandName, url: SITE },
    },
    { '@type': 'WebSite', name: SITE_NAME, url: SITE },
  ],
});

/** Which tags a page already set through `generateMetadata()` (name / property / rel=canonical). */
const tagsSetByPage = (headNodes: unknown): Set<string> => {
  const set = new Set<string>();
  for (const n of Children.toArray(headNodes as React.ReactNode)) {
    if (!isValidElement(n)) continue;
    const { name, property, rel } = (n.props ?? {}) as { name?: string; property?: string; rel?: string };
    if (n.type === 'title') set.add('title');
    if (n.type === 'meta' && (name || property)) set.add(String(name ?? property));
    if (n.type === 'link' && rel === 'canonical') set.add('canonical');
  }
  return set;
};

export default function Root({ children }: PropsWithChildren) {
  const { headNodes, bodyNodes, htmlAttributes, bodyAttributes } = useServerDocumentContext();
  // A page's own metadata (generateMetadata) wins; these are only the site-wide defaults.
  const own = tagsSetByPage(headNodes);
  const unless = (key: string, node: React.ReactNode) => (own.has(key) ? null : node);

  return (
    <html lang="en" {...htmlAttributes}>
      <head>
        <meta charSet="utf-8" />
        <meta httpEquiv="X-UA-Compatible" content="IE=edge" />
        <meta name="viewport" content="width=device-width, initial-scale=1, shrink-to-fit=no" />
        <ScrollViewStyleReset />
        {/* The app is a fixed full-screen view: the page itself never scrolls or pans sideways (mobile browsers included). */}
        <style dangerouslySetInnerHTML={{ __html: 'html,body{overflow:hidden;overscroll-behavior:none;width:100%;height:100%}#root{overflow:hidden}input:focus,textarea:focus{outline:none}' }} />
        {headNodes}

        {unless('title', <title>{DEFAULT_TITLE}</title>)}
        {unless('description', <meta name="description" content={DEFAULT_DESCRIPTION} />)}
        {unless('keywords', <meta name="keywords" content={KEYWORDS.join(', ')} />)}
        {unless('robots', <meta name="robots" content="index, follow, max-image-preview:large" />)}
        {unless('canonical', <link rel="canonical" href={SITE} />)}
        <meta name="application-name" content={SITE_NAME} />
        <meta name="apple-mobile-web-app-title" content={SITE_NAME} />
        <meta name="theme-color" content="#2450DB" />
        <meta name="color-scheme" content="dark light" />

        {/* Icons: favicon.ico is generated by Expo from assets/images/favicon.png (app.config.ts → web.favicon). */}
        <link rel="icon" href="/favicon.svg" type="image/svg+xml" />
        <link rel="icon" href="/favicon-48.png" type="image/png" sizes="48x48" />
        <link rel="icon" href="/favicon-32.png" type="image/png" sizes="32x32" />
        <link rel="apple-touch-icon" href="/apple-touch-icon.png" sizes="180x180" />
        <link rel="manifest" href="/manifest.webmanifest" />

        {unless('og:type', <meta property="og:type" content="website" />)}
        {unless('og:site_name', <meta property="og:site_name" content={SITE_NAME} />)}
        {unless('og:url', <meta property="og:url" content={SITE} />)}
        {unless('og:title', <meta property="og:title" content={DEFAULT_TITLE} />)}
        {unless('og:description', <meta property="og:description" content={DEFAULT_DESCRIPTION} />)}
        {unless('og:image', <meta property="og:image" content={SHARE_IMAGE} />)}
        {unless('og:image:width', <meta property="og:image:width" content="1200" />)}
        {unless('og:image:height', <meta property="og:image:height" content="630" />)}
        {unless('og:image:alt', <meta property="og:image:alt" content={SHARE_IMAGE_ALT} />)}
        {unless('og:locale', <meta property="og:locale" content="en_IN" />)}

        {unless('twitter:card', <meta name="twitter:card" content="summary_large_image" />)}
        {unless('twitter:title', <meta name="twitter:title" content={DEFAULT_TITLE} />)}
        {unless('twitter:description', <meta name="twitter:description" content={DEFAULT_DESCRIPTION} />)}
        {unless('twitter:image', <meta name="twitter:image" content={SHARE_IMAGE} />)}

        <script type="application/ld+json" dangerouslySetInnerHTML={{ __html: STRUCTURED_DATA }} />
      </head>
      <body {...bodyAttributes}>
        {/* Search engines and browsers without JavaScript still get what the site is. */}
        <noscript>
          <h1>{SITE_NAME}</h1>
          <p>{DEFAULT_DESCRIPTION}</p>
        </noscript>
        {children}
        {bodyNodes}
      </body>
    </html>
  );
}
